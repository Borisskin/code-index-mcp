/// Описание привязки, если процедура `proc_name` в модуле `rel_path` — обработчик
/// платформы по соглашению. `None` — не обработчик (обычная процедура модуля).
pub(crate) fn convention(rel_path: &str, proc_name: &str) -> Option<&'static str> {
    let list = match module_kind(rel_path)? {
        "object" => OBJECT_HANDLERS,
        "manager" => MANAGER_HANDLERS,
        "recordset" => RECORDSET_HANDLERS,
        "valuemanager" => VALUE_MANAGER_HANDLERS,
        "command" => COMMAND_HANDLERS,
        "form" => FORM_HANDLERS,
        _ => return None,
    };
    let low = proc_name.to_lowercase();
    list.iter()
        .find(|(n, _)| n.to_lowercase() == low)
        .map(|(_, d)| *d)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn posting_handler_is_recognized_in_object_module() {
        let d = convention(
            "base/Documents/Реализация/Ext/ObjectModule.bsl",
            "ОбработкаПроведения",
        );
        assert!(d.is_some_and(|d| d.contains("проведение")));
    }

    #[test]
    fn same_name_in_common_module_is_not_a_handler() {
        // `ПередЗаписью` в общем модуле — обычная процедура: её кто-то зовёт кодом.
        assert_eq!(
            convention("base/CommonModules/Обмен/Ext/Module.bsl", "ПередЗаписью"),
            None
        );
    }

    #[test]
    fn form_and_command_modules_are_recognized() {
        assert!(convention(
            "base/Documents/X/Forms/ФормаДокумента/Ext/Form/Module.bsl",
            "ПриСозданииНаСервере"
        )
        .is_some());
        assert!(convention(
            "base/Documents/X/Forms/ФормаДокумента/Ext/Form/Command/Module.bsl",
            "ОбработкаКоманды"
        )
        .is_some());
        assert!(convention(
            "base/Documents/X/Ext/Command/Module.bsl",
            "ОбработкаКоманды"
        )
        .is_some());
    }

    #[test]
    fn unknown_procedure_is_not_a_handler() {
        assert_eq!(
            convention("base/Documents/X/Ext/ObjectModule.bsl", "ЗаполнитьТовары"),
            None
        );
    }
}
