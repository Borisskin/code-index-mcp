//! Обработчики, которые платформа 1С вызывает по соглашению об имени.
//!
//! Самый частый случай — проведение документа: процедуру `ОбработкаПроведения`
//! не вызывает ни одна строка кода, её вызывает платформа, увидев процедуру с
//! таким именем в модуле объекта. В графе вызовов такого ребра нет и быть не
//! может — как и у подписок с событиями форм. Поэтому `get_callers` по такому
//! обработчику отвечал «вызывающих нет», и это читалось как «код мёртвый».
//!
//! Отличие от подписок и событий форм: там привязка записана в метаданных
//! (`EventSubscriptions/*.xml`, `Form.xml`), и адрес берётся оттуда. Здесь
//! записи нет вовсе — привязка держится на имени процедуры и виде модуля.
//!
//! Список сознательно неполон: в него попало то, что встречается в реальных
//! конфигурациях и опознаётся однозначно. Имя в отрыве от вида модуля ничего не
//! значит (`ПередЗаписью` есть и в модуле объекта, и в наборе записей, и в
//! форме), поэтому решение принимается по пути файла.

/// Вид модуля по пути выгрузки. `None` — вид неизвестен, соглашения не
/// применяются: у общего модуля обработчиков платформы нет.
fn module_kind(rel_path: &str) -> Option<&'static str> {
    let p = rel_path.replace('\\', "/");
    if p.ends_with("/Ext/ObjectModule.bsl") {
        return Some("object");
    }
    if p.ends_with("/Ext/ManagerModule.bsl") {
        return Some("manager");
    }
    if p.ends_with("/Ext/RecordSetModule.bsl") {
        return Some("recordset");
    }
    if p.ends_with("/Ext/ValueManagerModule.bsl") {
        return Some("valuemanager");
    }
    // Модуль команды: у объекта (`.../Ext/Command/Module.bsl`) и у формы
    // (`.../Forms/<форма>/Ext/Form/Command/Module.bsl`).
    if p.ends_with("/Ext/Command/Module.bsl") || p.ends_with("/Form/Command/Module.bsl") {
        return Some("command");
    }
    if p.contains("/Forms/") && p.ends_with("/Ext/Form/Module.bsl") {
        return Some("form");
    }
    None
}

