//! Глобальные функции и коллекции платформы 1С: вызовы, у которых определения
//! в конфигурации нет и быть не может.
//!
//! Зачем это нужно отдельным списком. В графе вызовов такие рёбра выглядят как
//! «вызов с пустым адресом цели» — ровно так же, как вызов, который резолвер не
//! смог разобрать. Разница принципиальная:
//!
//! * неразрешённый вызов кода — дефект связывания, его надо чинить;
//! * вызов платформенной функции — норма, адреса в конфигурации у него нет.
//!
//! Пока эти два класса смешаны, страдает не только статистика. Канал «прощение
//! по имени» в анализе неиспользуемого кода считает процедуру живой, если её имя
//! совпало с именем неразрешённого ребра, — а совпадает оно чаще всего именно с
//! платформенной функцией (`Число`, `Дата`, `Окр`, `НРег`). Отсюда правило
//! классификации: имя уходит в платформенные ТОЛЬКО если в этой конфигурации у
//! него нет ни одного определения (см. `classify_platform_calls`).
//!
//! Список не претендует на полноту: он собран по замерам на живой конфигурации
//! (имена с 20 и более вызовами — это 98,6 % всех таких рёбер) и пополняется по
//! мере надобности. Длинный хвост имён с 1–4 вызовами сознательно оставлен
//! неразрешённым: там встречаются опечатки и вызовы кода, которого нет в
//! выгрузке, — записывать их в платформенные было бы враньём.
//!
//! Регистр в 1С не значим, поэтому сравнение идёт по имени в нижнем регистре.
//! Именно поэтому имена в списке продублированы в разных написаниях, которые
//! реально встречаются в коде (`НРег` / `нрег` / `Нрег`, `Окр` / `ОКР`).

