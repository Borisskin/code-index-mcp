/// Список в нижнем регистре для сравнения: `SQLite` не умеет сворачивать
/// кириллицу функцией `lower()`, а `to_lowercase()` в Rust — умеет.
pub(crate) fn platform_globals_lower() -> Vec<String> {
    PLATFORM_GLOBALS
        .iter()
        .map(|n| n.to_lowercase())
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_has_no_duplicates_after_lowercasing() {
        let lower = platform_globals_lower();
        let raw: std::collections::BTreeSet<String> =
            PLATFORM_GLOBALS.iter().map(|n| n.to_lowercase()).collect();
        assert_eq!(
            lower.len(),
            raw.len(),
            "после сворачивания регистра должны остаться только уникальные имена"
        );
    }

    #[test]
    fn known_platform_names_are_present() {
        for name in [
            "Число",
            "Дата",
            "НРег",
            "Окр",
            "ПоказатьВопрос",
            "НачалоДня",
        ] {
            assert!(
                PLATFORM_GLOBALS.contains(&name),
                "{name} обязана быть в списке платформенных"
            );
        }
    }
}
